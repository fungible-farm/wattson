"""M04 — dataset factory self-check.

Runs the full M04 pipeline (generate -> validate -> deduplicate -> split) on a
small (2-per-subfamily = 10-example) dataset in a temp dir, and verifies the
M04 acceptance properties that are cheap to check in a test:
  * every example is schema-conformant with full provenance + execution evidence
  * no task-definition collisions / non-determinism
  * benchmark topologies are reserved and uncontaminated
  * identical inputs reproduce identical tasks + expected results (determinism)

The 500-example smoke dataset (the actual M04 deliverable) is generated by
`uv run python powercoder/datasets/generate.py --out-dir powercoder/datasets/smoke`
and is not re-derived here (it takes ~2.5 min); this test keeps the pipeline
honest on a fast subset.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT))

from wattson.datasets import common, generate, split  # noqa: E402
from wattson.datasets.deduplicate import deduplicate  # noqa: E402
from wattson.datasets.validate import validate_dataset  # noqa: E402

COUNT_PER_SUBFAMILY = 2  # 10 examples total — fast enough for a test.


def _gen(out_dir: Path, base_seed: int = 42) -> None:
    generate.main([
        "--base-seed", str(base_seed),
        "--count-per-subfamily", str(COUNT_PER_SUBFAMILY),
        "--out-dir", str(out_dir),
    ])


def test_m04_pipeline_end_to_end(tmp_path: Path) -> None:
    out = tmp_path / "ds"
    _gen(out)

    examples_path = out / "examples.jsonl"
    assert examples_path.exists()
    examples = common.load_jsonl(examples_path)
    assert len(examples) == 5 * COUNT_PER_SUBFAMILY

    # All examples verified (no quarantines on this subset).
    assert all(e["lifecycle"]["status"] == "verified" for e in examples)

    # validate: schema + provenance + execution evidence.
    report = validate_dataset(examples_path)
    assert report["failed"] == 0, report["failures"]
    assert report["passed"] == len(examples)

    # deduplicate: no collisions, no non-determinism.
    dedup_path = out / "dedup.jsonl"
    dedup_report = deduplicate(examples_path, dedup_path)
    assert dedup_report["nondeterministic"] == 0
    assert dedup_report["task_collisions"] == 0
    assert dedup_report["unique"] == len(examples)

    # split: benchmark reserved, no contamination.
    splits_dir = out / "splits"
    from wattson.datasets.split import split_dataset
    split_report = split_dataset(dedup_path, splits_dir)
    total = sum(split_report["counts"].values())
    assert total == len(examples)
    # No benchmark topology in train/val/test.
    for name in ("train", "validation", "test"):
        for e in common.load_jsonl(splits_dir / f"{name}.jsonl"):
            assert e["topology"] not in split.BENCHMARK_TOPOLOGIES


def test_m04_determinism(tmp_path: Path) -> None:
    a = tmp_path / "a"
    b = tmp_path / "b"
    _gen(a)
    _gen(b)

    def canon(p: Path) -> list[dict]:
        rows = common.load_jsonl(p / "examples.jsonl")
        for r in rows:
            r["provenance"].pop("created_utc", None)
            r["execution"].pop("execution_time_s", None)
        return rows

    ra, rb = canon(a), canon(b)
    assert [r["example_id"] for r in ra] == [r["example_id"] for r in rb]
    assert [json.dumps(r["task"], sort_keys=True) for r in ra] == \
           [json.dumps(r["task"], sort_keys=True) for r in rb]
    assert [json.dumps(r["expected"], sort_keys=True) for r in ra] == \
           [json.dumps(r["expected"], sort_keys=True) for r in rb]


if __name__ == "__main__":
    raise SystemExit(pytest.main([__file__, "-v"]))
