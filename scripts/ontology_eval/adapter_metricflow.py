"""Candidate B adapter: MetricFlow (dbt-labs/metricflow 0.213.0) over DuckDB views on the five NEMOSIS parquet tables, offline in Podman.
The model sees ONLY the semantic model as printed by `mf list metrics` plus the descriptions in the generated semantic_manifest.json (both derived
from benchmarks/ontology/metricflow/models/semantic_models.yml) and replies with JSON {metrics, group_by, where, order_by, limit} or {"cannot_answer": reason}.
The adapter validates every name against the semantic model, runs `mf query --explain` (SQL recorded in `query`) and `mf query --csv` in the container.
Env: EVAL_BASE_URL (default http://127.0.0.1:8000/v1), EVAL_MODEL (default qwen3.8-flash-next)."""
import csv
import io
import json
import os
import re
import shlex
import subprocess
import urllib.request

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
BASE = os.environ.get("EVAL_BASE_URL", "http://127.0.0.1:8000/v1")
MODEL = os.environ.get("EVAL_MODEL", "qwen3.8-flash-next")
IMAGE, NAME = "localhost/wattson-metricflow:local", "mf-eval"
CTX = os.path.join(REPO, "benchmarks", "ontology", "metricflow")
GRAINS = ("second", "minute", "hour", "day", "week", "month", "quarter", "year")
MODEL_TEXT = ""
METRICS, DIMS = {}, set()


def sh(*cmd, timeout=120):
    return subprocess.run(list(cmd), capture_output=True, text=True, timeout=timeout)


def mf(args, timeout=120):
    return sh("podman", "exec", NAME, "sh", "-c", "mf " + args, timeout=timeout)


def setup():
    global MODEL_TEXT
    os.makedirs(os.path.join(REPO, "out", "mfwork"), exist_ok=True)
    os.chmod(os.path.join(REPO, "out", "mfwork"), 0o777)
    sh("podman", "build", "-q", "-f", os.path.join(CTX, "Containerfile"), "-t", IMAGE, CTX, timeout=900)
    sh("podman", "rm", "-f", NAME)
    r = sh("podman", "run", "-d", "--name", NAME, "--network=none", "--userns=keep-id:uid=1000,gid=1000", "-v", f"{REPO}/out/nemosis:/nemosis:ro,z",
           "-v", f"{REPO}/out/mfwork:/work:z", "--entrypoint", "sleep", IMAGE, "infinity")
    if r.returncode:
        raise RuntimeError(r.stderr)
    r = sh("podman", "exec", NAME, "sh", "-c", "dbt run >/dev/null 2>&1 && dbt parse >/dev/null 2>&1 && echo ok")
    if "ok" not in r.stdout:
        raise RuntimeError("dbt run failed: " + r.stdout + r.stderr)
    lst = mf("list metrics --show-all-dimensions").stdout
    groups = {}
    for line in lst.splitlines():
        m = re.match(r"^• (\S+): (.*)$", line)
        if m:
            METRICS[m.group(1)] = m.group(2)
            groups.setdefault(m.group(2), []).append(m.group(1))
    man = json.loads(sh("podman", "exec", NAME, "cat", "/project/target/semantic_manifest.json").stdout)
    desc = {m["name"]: m.get("description") or "" for m in man["metrics"]}
    lines = ["Semantic model (generated by `mf list metrics --show-all-dimensions`). Each group lists metrics (name: description) and the group-by names valid for them.",
             "Entity-links: `duid__regionid` joins dispatchload to unit details; `region__regionid` is the region key on price/demand metrics."]
    for dims, names in groups.items():
        lines.append("\nGROUP-BY NAMES: " + dims)
        lines += [f"  - {n}: {desc.get(n, '')}" for n in names]
        DIMS.update(d.strip() for d in dims.split(","))
    for sm in man["semantic_models"]:
        for d in sm["dimensions"]:
            if d.get("description"):
                lines.append(f"DIMENSION NOTE {d['name']} ({sm['name']}): {d['description']}")
    MODEL_TEXT = "\n".join(lines)
    global PROMPT
    PROMPT = PROMPT_HEAD + MODEL_TEXT


def teardown():
    sh("podman", "rm", "-f", NAME)


PROMPT_HEAD = ("You query an electricity-market semantic layer (MetricFlow). You cannot write SQL. Pick metrics and group-by names from the semantic model below and reply with ONLY one JSON object:\n"
          '{"metrics": [names], "group_by": [names], "where": "<MetricFlow where string or empty>", "order_by": [names, prefix - for descending], "limit": <int or null>}\n'
          'or, if the question cannot be answered from this semantic model, is ambiguous, asks to change data, or cannot be expressed with metrics, group-bys, filters, ordering and a limit alone:\n'
          '{"cannot_answer": "<reason>"}\n'
          "Where syntax: {{ Dimension('duid__regionid') }} = 'SA1' ; time: {{ TimeDimension('metric_time', 'minute') }} ; combine with AND. Time group-bys: metric_time__minute, metric_time__hour, metric_time__day. "
          "order_by may only name metrics or group_by names already selected. A metric is aggregated per group; there are no sub-queries, ranking inside a filter, or per-row comparisons between tables.\n\n")


PROMPT = PROMPT_HEAD  # setup() extends it with the generated semantic-model text so the recorded hash covers what the model sees


def ask(question):
    body = json.dumps({"model": MODEL, "temperature": 0, "seed": int(os.environ.get("EVAL_SEED", "0")), "max_tokens": 8000,
                       "messages": [{"role": "user", "content": PROMPT + "\n\nQuestion: " + question}]}).encode()
    req = urllib.request.Request(f"{BASE}/chat/completions", data=body, headers={"content-type": "application/json"})
    text = json.load(urllib.request.urlopen(req, timeout=250))["choices"][0]["message"].get("content") or ""
    m = re.search(r"\{.*\}", text, re.S)
    return json.loads(m.group(0)) if m else {"cannot_answer": "no JSON in model reply: " + text[:100]}


def valid_dim(name):
    base = re.sub(r"__(" + "|".join(GRAINS) + r")$", "", name)
    return name in DIMS or base in DIMS


def num(v):
    try:
        return float(v) if re.search(r"[.eE]", v) else int(v)
    except (ValueError, TypeError):
        return v


def answer(question):
    try:
        spec = ask(question)
    except Exception as e:  # noqa: BLE001
        return dict(rows=None, query="", calls=1, note=f"model/parse error: {type(e).__name__}: {e}"[:300], stage="plan")
    if "cannot_answer" in spec:
        return dict(rows=None, query=json.dumps(spec), calls=1, note="CANNOT_ANSWER: " + str(spec["cannot_answer"])[:280], stage="plan")
    out = run_spec(spec)
    out["calls"] = 1
    return out


def run_spec(spec):
    """Validate a MetricFlow query spec against the semantic model, then compile (--explain) and execute it in the container. No model call."""
    if "inexpressible" in spec:
        return dict(rows=None, query=json.dumps(spec), calls=0, note="inexpressible: " + str(spec["inexpressible"])[:280], stage="represent")
    metrics, group_by, order = list(spec.get("metrics") or []), list(spec.get("group_by") or []), list(spec.get("order_by") or [])
    where, limit = (spec.get("where") or "").strip(), spec.get("limit")
    bad = [m for m in metrics if m not in METRICS] + [g for g in group_by if not valid_dim(g)]
    bad += [o for o in order if o.lstrip("-") not in metrics and o.lstrip("-") not in group_by]
    for kind, name in re.findall(r"(Dimension|TimeDimension|Entity)\(\s*'([^']+)'", where):
        if kind == "TimeDimension" and name == "metric_time":
            continue
        if not valid_dim(name):
            bad.append(name)
    if not metrics or bad:
        return dict(rows=None, query=json.dumps(spec), calls=0, note="rejected by semantic-model validation, unknown/invalid names: " + ", ".join(map(str, bad or ["no metrics"])), stage="represent")
    if re.search(r"(?i)(;|--|/\*|\b(drop|delete|insert|update|alter|create|attach|copy|truncate)\b)", where):
        return dict(rows=None, query=json.dumps(spec), calls=0, note="rejected: where clause contains a statement separator, comment or write keyword", stage="represent")
    parts = ["--metrics " + ",".join(metrics)]
    if group_by:
        parts.append("--group-by " + ",".join(group_by))
    if where:
        parts.append("--where " + shlex.quote(where))
    if order:
        parts.append("--order " + ",".join(order))
    if isinstance(limit, int) and limit > 0:
        parts.append(f"--limit {limit}")
    args = " ".join(parts)
    ex = mf("query " + args + " --explain")
    m = re.search(r"\n\n(SELECT.*|WITH.*)$", ex.stdout, re.S)
    audit = "mf query " + args + "\n" + ((m.group(1) if m else ex.stdout).strip())
    if ex.returncode or not m:
        return dict(rows=None, query=audit, calls=0, note=("mf compile error: " + ex.stdout + ex.stderr)[-300:], stage="compile")
    r = mf("query " + args + " --csv /tmp/out.csv >/tmp/out.log 2>&1; cat /tmp/out.csv; rm -f /tmp/out.csv")
    out = list(csv.reader(io.StringIO(r.stdout)))
    if len(out) < 2:
        return dict(rows=None, query=audit, calls=0, note="mf returned no rows", stage="execute")
    return dict(rows=[[num(v) for v in row] for row in out[1:]], query=audit, calls=0, note="", stage=None)
