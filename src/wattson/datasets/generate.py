# --- generation parameters (named, with provenance) -------------------------

# Global load/line-rating/dispatch scale search interval. Chosen to match the
# element-discovery sweep (scripts/wattson-discover-elements.py) so the
# curated element lists' measured endpoint ranges apply directly.
SCALE_LO: float = 0.90
SCALE_HI: float = 1.10

# Targets are placed a fraction of the way between the element's measured
# endpoint metrics, avoiding the endpoints themselves (which are already
# "solved" at the bounds) and keeping the fit well inside the bracket.
TARGET_FRACTION_LO: float = 0.10
TARGET_FRACTION_HI: float = 0.90

# Convergence tolerance for the fit search, expressed as a FRACTION of the
# element's measured metric span over [SCALE_LO, SCALE_HI]. A fixed absolute
# tolerance (e.g. Lab 3's 0.5%) is meaningless for the generated dataset:
# the per-element spans differ by orders of magnitude (line loadings here are
# ~0.1% vs Lab 3's ~100%), so a fixed tolerance is either trivially loose
# (fit stops at the s=1.0 midpoint) or impossibly tight (no convergence).
# 2% of the span is non-trivial (the target is well-separated) yet reachable
# in ~6-8 bisection iterations (interval halves to span/64 < 0.02*span).
TOL_FRACTION_OF_SPAN: float = 0.02
# Floor so a near-flat metric (tiny span) still yields a usable, positive
# tolerance rather than a sub-precision one.
TOL_ABS_FLOOR: float = 1e-4

# Lab 3's original per-metric tolerances, kept for reference / traceability to
# the source task family (NOT used for the generated dataset's fit search —
# see TOL_FRACTION_OF_SPAN above).
FIT_TOLERANCES: dict[str, float] = {
    "pf-load-scale-fit": 0.002,      # pu (voltage)
    "pf-line-rating-fit": 0.5,       # percent (line loading)
    "pf-gen-dispatch-fit": 0.5,      # percent (transformer loading)
}

# Default per-subfamily counts for the 500-example smoke dataset. Sums to 500.
# gen-dispatch gets fewer because element discovery found only 4 valid
# (gen, trafo) pairs on snem-sa-2000; the others have 42-68 candidate elements.
DEFAULT_COUNTS: dict[str, int] = {
    "pf-report": 120,
    "pf-load-scale-fit": 120,
    "pf-line-rating-fit": 120,
    "pf-gen-dispatch-fit": 40,
    "mcp-trajectory": 100,
}

# Per-subfamily case (topology) lists. Fit families use only snem-sa-2000
# (the element lists were discovered there); report/trajectory use both cases
# to give the dataset two topologies for split partitioning.
SUBFAMILY_CASES: dict[str, list[str]] = {
    "pf-report": ["snem-sa-2000", "fixture-2bus-ok"],
    "pf-load-scale-fit": ["snem-sa-2000"],
    "pf-line-rating-fit": ["snem-sa-2000"],
    "pf-gen-dispatch-fit": ["snem-sa-2000"],
    "mcp-trajectory": ["snem-sa-2000", "fixture-2bus-ok"],
}

# A case needs more than this many lines before an N-1 line-contingency report
# is meaningful (tripping the only line of the 2-bus fixture disconnects the
# load entirely).
MIN_LINES_FOR_CONTINGENCY: int = 5


# --- solver helpers (real pp.runpp only) ------------------------------------

def _solve(net: pp.pandapowerNet) -> tuple[int, float, float, int]:
    """Run the canonical pp.runpp on `net` and return key measurements.

    Returns:
        (iterations, vm_min_pu, vm_max_pu, n_voltage_violations) -- all real
        solver output. Raises pp.LoadflowNotConverged (non-convergence) or
        whatever pp.runpp raises (execution failure) on the caller.
    """
    iters = pm._runpp_counted(net, numba=True)
    vm = net.res_bus["vm_pu"]
    vm_min, vm_max = float(vm.min()), float(vm.max())
    viol = int(((vm < pm.VOLTAGE_LIMIT_LOW_PU) | (vm > pm.VOLTAGE_LIMIT_HIGH_PU)).sum())
    return iters, vm_min, vm_max, viol


def _max_line_loading(net: pp.pandapowerNet) -> float:
    """Max line loading percent from the last solver run (0.0 if no lines)."""
    return float(net.res_line["loading_percent"].max()) if len(net.line) else 0.0


class EndpointCache:
    """Caches per-(case, element) fit metrics to cut solver runs.

    The metrics at SCALE_LO, 1.0 (base case), and SCALE_HI depend only on
    (case, element), not on the per-example target/seed, so they are computed
    once per distinct element and reused across every example that picks that
    element. The base-case midpoint (m_mid) is what lets the target be placed
    on one side of the trivial s=1.0 answer.
    """

    def __init__(self) -> None:
        self._cache: dict[tuple[Any, ...], tuple[float, float, float]] = {}

    def get(self, key: tuple[Any, ...], compute: Callable[[], tuple[float, float, float]]) -> tuple[float, float, float]:
        if key not in self._cache:
            self._cache[key] = compute()
        return self._cache[key]


def _load_element_lists(path: Path) -> dict[str, Any]:
    """Load the curated element lists (scripts/wattson-discover-elements.py)."""
    import json

    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


# --- fit-task machinery ------------------------------------------------------

# A modifier takes (base_net, scale) and returns a FRESH net with the scaled
# element applied (always a deep copy, so the base net is never mutated across
# trials). A reader takes a solved net and returns the scalar fit metric.
Modifier = Callable[[pp.pandapowerNet, float], pp.pandapowerNet]
Reader = Callable[[pp.pandapowerNet], float]


def _modifier_load_scale(base: pp.pandapowerNet, s: float) -> pp.pandapowerNet:
    """Scale every load's p_mw/q_mvar by s (gridfit.scale_loads deep-copies)."""
    return scale_loads(base, s)


def _make_modifier_line_rating(line_id: int) -> Modifier:
    def mod(base: pp.pandapowerNet, s: float) -> pp.pandapowerNet:
        n = copy.deepcopy(base)
        n.line.loc[line_id, "max_i_ka"] = n.line.loc[line_id, "max_i_ka"] * s
        return n

    return mod


def _make_modifier_gen_dispatch(gen_id: int) -> Modifier:
    def mod(base: pp.pandapowerNet, s: float) -> pp.pandapowerNet:
        n = copy.deepcopy(base)
        n.gen.loc[gen_id, "p_mw"] = n.gen.loc[gen_id, "p_mw"] * s
        return n

    return mod


def _reader_bus_voltage(bus_id: int) -> Reader:
    return lambda net: float(net.res_bus.loc[bus_id, "vm_pu"])


def _reader_line_loading(line_id: int) -> Reader:
    return lambda net: float(net.res_line.loc[line_id, "loading_percent"])


def _reader_trafo_loading(trafo_id: int) -> Reader:
    return lambda net: float(net.res_trafo.loc[trafo_id, "loading_percent"])


def with_outage(modifier: Modifier, line: int | None) -> Modifier:
    """``modifier`` applied to the network with ``line`` out of service (identity for None)."""
    if line is None:
        return modifier

    def mod(base: pp.pandapowerNet, s: float) -> pp.pandapowerNet:
        n = copy.deepcopy(base)
        n.line.loc[line, "in_service"] = False
        return modifier(n, s)

    return mod


def with_load_level(modifier: Modifier, level: float | None) -> Modifier:
    """``modifier`` applied at an operating point: every load times ``level`` first (identity for None)."""
    if level is None:
        return modifier

    def mod(base: pp.pandapowerNet, s: float) -> pp.pandapowerNet:
        return modifier(scale_loads(base, level), s)

    return mod


def _make_evaluate(case: str, modifier: Modifier, reader: Reader) -> Callable[[float], float]:
    """Build evaluate(s) -> metric: a fresh scaled net, a real pp.runpp, then
    the reader. This is the real-solver `evaluate` that bisection_fit drives."""
    base_net, _ = pm._load_network_object(case)

    def evaluate(s: float) -> float:
        net = modifier(base_net, s)
        _solve(net)
        return reader(net)

    return evaluate


@dataclass
class FitSpec:
    """Everything needed to generate one fit-family example."""

    subfamily: str
    case: str
    element_desc: str          # human-readable element (for the prompt)
    element_key: tuple[Any, ...]  # cache key for endpoint metrics
    modifier: Modifier
    reader: Reader
    metric_unit: str           # 'pu' or 'percent'
    metric_name: str           # 'bus voltage' / 'line loading' / 'transformer loading'
    target_label: str          # 'target voltage' / 'target loading'


def _run_fit(spec: FitSpec, target: float, tol: float) -> dict[str, Any]:
    """Execute one fit task with real bisection + a final real solver run.

    Returns a dict with the fitted scalar, the final operating point, and the
    canonical execution evidence. Every number is real solver output.
    """
    evaluate = _make_evaluate(spec.case, spec.modifier, spec.reader)
    fit = bisection_fit(evaluate, target, SCALE_LO, SCALE_HI, tol)

    # Final real solver run at the fitted scale -> the expected operating point.
    base_net, input_hash = pm._load_network_object(spec.case)
    final_net = spec.modifier(base_net, fit.trial)
    try:
        iters, vm_min, vm_max, viol = _solve(final_net)
        status = pm.ExecutionStatus.CONSTRAINT_VIOLATION if viol else pm.ExecutionStatus.SUCCESS
        physical_valid = viol == 0
        diagnostics = (
            [f"{viol} bus voltages outside {pm.VOLTAGE_LIMIT_LOW_PU}-{pm.VOLTAGE_LIMIT_HIGH_PU} pu"]
            if viol
            else []
        )
    except pp.LoadflowNotConverged:
        iters, vm_min, vm_max, viol = None, None, None, None
        status = pm.ExecutionStatus.NON_CONVERGENCE
        physical_valid = False
        diagnostics = ["final operating point did not converge"]
    except Exception as e:  # execution failure at the fitted point
        iters, vm_min, vm_max, viol = None, None, None, None
        status = pm.ExecutionStatus.EXECUTION_FAILURE
        physical_valid = False
        diagnostics = [f"{type(e).__name__}: {e}"]

    result_payload: dict[str, Any] = {
        "status": status.value,
        "fitted_scale": fit.trial,
        "target": target,
        "achieved_metric": fit.observed,
        "converged": fit.converged,
        "iterations": iters,
        "min_bus_voltage_pu": vm_min,
        "max_bus_voltage_pu": vm_max,
        "voltage_violations": viol,
        "max_line_loading_percent": _max_line_loading(final_net) if len(getattr(final_net, "res_line", [])) else None,
    }
    evidence = pm.PowerMCP._canonical_evidence(
        case_id=spec.case,
        tool_name=spec.subfamily,
        input_hash=input_hash,
        status=status,
        result_payload=result_payload,
        diagnostics=diagnostics,
        physical_valid=physical_valid,
    )
    return {
        "fitted_scale": fit.trial,
        "converged": fit.converged,
        "achieved_metric": fit.observed,
        "residual": fit.residual,
        "fit_iterations": len(fit.iterations),
        "final_status": status,
        "final_evidence": evidence,
        "physical_valid": physical_valid,
    }


# --- per-subfamily example builders -----------------------------------------

# Prompt wordings. v1 (to 2026-10-23) said "applied to bus B" for a load-scale fit, which
# scales every load and observes bus B: incoherent, so a model told to refuse incoherent tasks
# could rightly refuse it. v2 names what the scale multiplies and what is observed, as the
# study tool does (user direction 2026-10-24).
PROMPT_WORDINGS: tuple[str, ...] = ("v1", "v2")
CURRENT_WORDING: str = "v2"
METRIC_NAMES: dict[str, str] = {"pf-load-scale-fit": "bus voltage", "pf-line-rating-fit": "line loading",
                                "pf-gen-dispatch-fit": "transformer loading"}


def fit_prompt(subfamily: str, inputs: dict[str, Any], wording: str = CURRENT_WORDING, interval: bool = True) -> str:
    """A fit task's prompt, rendered from its inputs alone.

    ``interval=False`` drops " in [lo, hi]" (the judgement suite's open-interval variant).

    Raises:
        ValueError: for an unknown wording or element description.
    """
    case, unit, tol = inputs["case"], inputs["metric_unit"], inputs["tolerance"]
    bracket = f" in [{inputs['scale_lo']}, {inputs['scale_hi']}]" if interval else ""
    goal = f"{inputs['target']:.6f} {unit} (within {tol} {unit}). Return only the scale factor."
    if wording == "v1":
        return (f"Using the power flow solver, find the scale factor s{bracket} applied to {inputs['element']} on case "
                f"'{case}' such that the {METRIC_NAMES[subfamily]} equals {goal}")
    if wording != "v2":
        raise ValueError(f"Unknown prompt wording {wording!r}")
    outage, level = inputs.get("contingency_line"), inputs.get("load_level")
    where = f"'{case}'" + (f" with line {outage} out of service (N-1 contingency)" if outage is not None else "") + (
        f" with every load at {level} times its base value" if level is not None else "")
    ids = [int(x) for x in re.findall(r"\d+", inputs["element"])]
    scaled, observed = {
        "pf-load-scale-fit": ("every load's active and reactive demand", f"voltage at bus {ids[-1]}"),
        "pf-line-rating-fit": (f"the thermal rating of line {ids[0]}", f"loading of line {ids[0]}"),
        "pf-gen-dispatch-fit": (f"the active-power dispatch of generator {ids[0]}", f"loading of transformer {ids[-1]}"),
    }[subfamily]
    return (f"Using the power flow solver, find the scale factor s{bracket} applied to {scaled} on case {where} "
            f"such that the {observed} equals {goal}")


def _gen_fit_example(
    subfamily: str,
    case: str,
    elements: list[Any],
    i: int,
    base_seed: int,
    cache: EndpointCache,
    contingency_line: int | None = None,
    load_level: float | None = None,
) -> dict[str, Any]:
    """Generate one fit-family example: pick an element (seeded), derive a
    target inside its measured endpoint range (seeded), fit with real
    bisection, and record the solver's output as the expected result."""
    family = "power-flow-contingency"
    seed = common.derive_example_seed(base_seed, family, subfamily, case, i)
    rng = random.Random(seed)
    element = elements[rng.randrange(len(elements))]

    if subfamily == "pf-load-scale-fit":
        bus = int(element["bus"])
        spec = FitSpec(
            subfamily=subfamily, case=case,
            element_desc=f"bus {bus}", element_key=(case, "load_scale", bus),
            modifier=_modifier_load_scale, reader=_reader_bus_voltage(bus),
            metric_unit="pu", metric_name="bus voltage", target_label="target voltage",
        )
    elif subfamily == "pf-line-rating-fit":
        line = int(element["line"])
        spec = FitSpec(
            subfamily=subfamily, case=case,
            element_desc=f"line {line}", element_key=(case, "line_rating", line),
            modifier=_make_modifier_line_rating(line), reader=_reader_line_loading(line),
            metric_unit="percent", metric_name="line loading", target_label="target loading",
        )
    else:  # pf-gen-dispatch-fit
        gen, trafo = int(element["gen"]), int(element["trafo"])
        spec = FitSpec(
            subfamily=subfamily, case=case,
            element_desc=f"generator {gen} (transformer {trafo})",
            element_key=(case, "gen_dispatch", gen, trafo),
            modifier=_make_modifier_gen_dispatch(gen), reader=_reader_trafo_loading(trafo),
            metric_unit="percent", metric_name="transformer loading", target_label="target loading",
        )

    if contingency_line is not None:
        # An N-1 fit (backlog 0017): the reference bisection, its endpoints and the final solve
        # all run with the line out, and the cache key keeps it apart from the intact fit.
        spec.modifier = with_outage(spec.modifier, contingency_line)
        spec.element_key = (*spec.element_key, "N-1", contingency_line)
    if load_level is not None:
        if subfamily == "pf-load-scale-fit":
            raise ValueError("a load-scale fit already scales every load; it has no separate operating point")
        # The operating point is applied before the outage and the fit's own modification, as the tool does.
        spec.modifier = with_load_level(spec.modifier, load_level)
        spec.element_key = (*spec.element_key, "level", load_level)

    # Endpoint metrics (cached per element): the metric at SCALE_LO, at the
    # base case (s=1.0), and at SCALE_HI. The metric is monotonic in s
    # (verified at discovery), so placing the target on ONE side of the
    # base-case metric m_mid guarantees the fitted scale factor is
    # meaningfully different from the trivial bisection midpoint s=1.0.
    evaluate = _make_evaluate(case, spec.modifier, spec.reader)
    m_lo, m_mid, m_hi = cache.get(
        spec.element_key,
        lambda: (evaluate(SCALE_LO), evaluate(1.0), evaluate(SCALE_HI)),
    )
    # Target one side of the base case (seeded). "above" -> target metric
    # between m_mid and m_hi -> answer s in (1.0, SCALE_HI]; "below" ->
    # between m_lo and m_mid -> answer s in [SCALE_LO, 1.0). Works for either
    # monotonic direction because we interpolate in metric space.
    mid_between = (min(m_lo, m_hi) <= m_mid <= max(m_lo, m_hi))
    if mid_between:
        side = rng.choice(["below", "above"])
        seg_lo, seg_hi = (m_mid, m_hi) if side == "above" else (m_lo, m_mid)
    else:
        # Non-monotonic / base case at an endpoint: fall back to the full range.
        seg_lo, seg_hi = m_lo, m_hi
    seg_span = seg_hi - seg_lo
    if abs(seg_span) < 1e-9:
        # Flat metric: no target can be bracketed; the fit will not converge
        # and the example is quarantined below.
        target = m_mid
    else:
        frac = TARGET_FRACTION_LO + rng.random() * (TARGET_FRACTION_HI - TARGET_FRACTION_LO)
        target = seg_lo + frac * seg_span
    # Tolerance scales with the metric span over [SCALE_LO, SCALE_HI] so the
    # fit is non-trivial (the target is well-separated from the base case) yet
    # achievable (~6-8 bisection iterations). A fixed absolute tolerance (e.g.
    # Lab 3's 0.5%) is meaningless here: the generated targets span metric
    # values far smaller than Lab 3's (line loadings ~0.1% vs Lab 3's ~100%),
    # which made the fit trivially converge at the s=1.0 midpoint.
    span = abs(m_hi - m_lo)
    tol = max(TOL_ABS_FLOOR, TOL_FRACTION_OF_SPAN * span)

    task_inputs = {
        "case": case,
        "element": spec.element_desc,
        "target": round(target, 6),
        "scale_lo": SCALE_LO,
        "scale_hi": SCALE_HI,
        "tolerance": tol,
        "metric_unit": spec.metric_unit,
    }
    if contingency_line is not None:
        task_inputs["contingency_line"] = contingency_line
    if load_level is not None:
        task_inputs["load_level"] = load_level
    prompt = fit_prompt(subfamily, task_inputs)

    run = _run_fit(spec, target, tol)
    status = run["final_status"]
    validity = {
        pm.ExecutionStatus.SUCCESS: "valid",
        pm.ExecutionStatus.CONSTRAINT_VIOLATION: "constraint_violation",
        pm.ExecutionStatus.NON_CONVERGENCE: "non_convergence",
        pm.ExecutionStatus.EXECUTION_FAILURE: "execution_failure",
    }[status]

    if run["converged"]:
        answer = (
            f"The scale factor is s = {run['fitted_scale']:.6f}. At this scale, "
            f"{spec.element_desc} gives {spec.metric_name} = "
            f"{run['achieved_metric']:.6f} {spec.metric_unit} (target {target:.6f}, "
            f"residual {abs(run['residual']):.6f})."
        )
    else:
        answer = (
            f"The fit did not converge to {tol} {spec.metric_unit} within the "
            f"iteration budget; the best scale factor is s = "
            f"{run['fitted_scale']:.6f} with {spec.metric_name} = "
            f"{run['achieved_metric']:.6f} {spec.metric_unit}."
        )

    structured = {
        "scale_factor": round(run["fitted_scale"], 6),
        "metric": round(run["achieved_metric"], 6),
        "target": round(target, 6),
        "converged": run["converged"],
        "fit_iterations": run["fit_iterations"],
    }
    ev = run["final_evidence"]
    example_id = common.compute_example_id(family, subfamily, case, seed, task_inputs)
    return {
        "example_id": example_id,
        "family": family,
        "subfamily": subfamily,
        "topology": case,
        "seed": seed,
        "task": {"prompt": prompt, "inputs": task_inputs},
        "expected": {"answer": answer, "structured": structured, "validity": validity},
        "execution": {
            "case_id": ev["case_id"],
            "solver": ev["solver"],
            "solver_version": ev["solver_version"],
            "input_hash": ev["input_hash"],
            "result_hash": ev["result_hash"],
            "status": ev["status"],
            "iterations": ev.get("iterations"),
            "execution_time_s": None,
        },
        "provenance": common.build_provenance(
            base_seed,
            source_refs=[
                f"case:{case}",
                "src/wattson/datasets/element_lists.json",
                "scripts/wattson-discover-elements.py",
                "MISSION.md#M04",
            ],
        ),
        "lifecycle": {"status": "verified" if run["converged"] else "quarantined",
                      "split": None,
                      "rejection_reason": None if run["converged"] else "fit did not converge to tolerance (retained for repair training)"},
    }


def _gen_pf_report_example(case: str, i: int, base_seed: int) -> dict[str, Any]:
    """Generate one power-flow report example (base case or N-1 line
    contingency), reporting the solver's own measurements."""
    family = "power-flow-contingency"
    subfamily = "pf-report"
    seed = common.derive_example_seed(base_seed, family, subfamily, case, i)
    rng = random.Random(seed)

    net, input_hash = pm._load_network_object(case)
    contingency_line: Optional[int] = None
    can_contingency = len(net.line) > MIN_LINES_FOR_CONTINGENCY
    if can_contingency and rng.random() < 0.5:
        contingency_line = int(net.line.index[rng.randrange(len(net.line))])
        net.line.loc[contingency_line, "in_service"] = False

    t0 = time.monotonic()
    try:
        iters, vm_min, vm_max, viol = _solve(net)
        max_load = _max_line_loading(net)
        status = pm.ExecutionStatus.CONSTRAINT_VIOLATION if viol else pm.ExecutionStatus.SUCCESS
        physical_valid = viol == 0
        diagnostics = (
            [f"{viol} bus voltages outside {pm.VOLTAGE_LIMIT_LOW_PU}-{pm.VOLTAGE_LIMIT_HIGH_PU} pu"]
            if viol else []
        )
    except pp.LoadflowNotConverged as e:
        iters, vm_min, vm_max, viol, max_load = None, None, None, None, None
        status = pm.ExecutionStatus.NON_CONVERGENCE
        physical_valid = False
        diagnostics = [str(e)]
    except Exception as e:
        iters, vm_min, vm_max, viol, max_load = None, None, None, None, None
        status = pm.ExecutionStatus.EXECUTION_FAILURE
        physical_valid = False
        diagnostics = [f"{type(e).__name__}: {e}"]
    elapsed = time.monotonic() - t0

    contingency_desc = (
        f" with line {contingency_line} out of service (N-1 contingency)"
        if contingency_line is not None else " (base case)"
    )
    task_inputs = {
        "case": case,
        "contingency_line": contingency_line,
    }
    prompt = (
        f"Run an AC power flow on case '{case}'{contingency_desc} and report the "
        f"result: convergence, iterations, min/max bus voltage (pu), max line "
        f"loading (percent), and the number of bus-voltage violations."
    )

    if status == pm.ExecutionStatus.SUCCESS or status == pm.ExecutionStatus.CONSTRAINT_VIOLATION:
        answer = (
            f"Power flow on '{case}'{contingency_desc} converged in {iters} "
            f"iterations. Min bus voltage = {vm_min:.4f} pu, max bus voltage = "
            f"{vm_max:.4f} pu, max line loading = {max_load:.2f}%, voltage "
            f"violations = {viol}."
        )
    elif status == pm.ExecutionStatus.NON_CONVERGENCE:
        answer = f"Power flow on '{case}'{contingency_desc} did not converge."
    else:
        answer = f"Power flow on '{case}'{contingency_desc} failed to execute."

    result_payload = {
        "status": status.value,
        "contingency_line": contingency_line,
        "iterations": iters,
        "min_bus_voltage_pu": vm_min,
        "max_bus_voltage_pu": vm_max,
        "max_line_loading_percent": max_load,
        "voltage_violations": viol,
    }
    evidence = pm.PowerMCP._canonical_evidence(
        case_id=case, tool_name="run_power_flow", input_hash=input_hash,
        status=status, result_payload=result_payload,
        diagnostics=diagnostics, physical_valid=physical_valid,
    )
    validity = {
        pm.ExecutionStatus.SUCCESS: "valid",
        pm.ExecutionStatus.CONSTRAINT_VIOLATION: "constraint_violation",
        pm.ExecutionStatus.NON_CONVERGENCE: "non_convergence",
        pm.ExecutionStatus.EXECUTION_FAILURE: "execution_failure",
    }[status]
    structured = {
        "converged": status in (pm.ExecutionStatus.SUCCESS, pm.ExecutionStatus.CONSTRAINT_VIOLATION),
        "iterations": iters,
        "min_bus_voltage_pu": vm_min,
        "max_bus_voltage_pu": vm_max,
        "max_line_loading_percent": max_load,
        "voltage_violations": viol,
    }
    example_id = common.compute_example_id(family, subfamily, case, seed, task_inputs)
    # A CONVERGED report is a valid training example whether or not it has
    # voltage violations (the model must report the violations, not hide them).
    # Quarantine only non-converged / execution-failed reports.
    converged = status in (pm.ExecutionStatus.SUCCESS, pm.ExecutionStatus.CONSTRAINT_VIOLATION)
    return {
        "example_id": example_id,
        "family": family,
        "subfamily": subfamily,
        "topology": case,
        "seed": seed,
        "task": {"prompt": prompt, "inputs": task_inputs},
        "expected": {"answer": answer, "structured": structured, "validity": validity},
        "execution": {
            "case_id": evidence["case_id"],
            "solver": evidence["solver"],
            "solver_version": evidence["solver_version"],
            "input_hash": evidence["input_hash"],
            "result_hash": evidence["result_hash"],
            "status": evidence["status"],
            "iterations": iters,
            "execution_time_s": elapsed,
        },
        "provenance": common.build_provenance(
            base_seed,
            source_refs=[f"case:{case}", "MISSION.md#M04"],
        ),
        "lifecycle": {"status": "verified" if converged else "quarantined",
                      "split": None,
                      "rejection_reason": None if converged else "non-converged / failed report"},
    }


def _gen_mcp_trajectory_example(case: str, i: int, base_seed: int) -> dict[str, Any]:
    """Generate one PowerMCP tool-trajectory example: load_network then
    run_power_flow, with the real tool results as the expected trajectory."""
    family = "powermcp-trajectories"
    subfamily = "mcp-trajectory"
    seed = common.derive_example_seed(base_seed, family, subfamily, case, i)
    rng = random.Random(seed)

    max_iter = rng.choice([20, 50, 100])
    check_limits = rng.random() < 0.8
    pmc = pm.PowerMCP()
    step1 = pmc.load_network(case)
    step2 = pmc.run_power_flow(case, method="nr", max_iter=max_iter, check_limits=check_limits)

    input_hash = step1.data.get("network_id") and pm._load_network_object(case)[1]
    trajectory = [
        {
            "tool": "load_network",
            "args": {"network_id": case},
            "status": step1.status.value,
            "result": step1.data if step1.status == pm.ExecutionStatus.SUCCESS else {"error": step1.error},
        },
        {
            "tool": "run_power_flow",
            "args": {"network_id": case, "method": "nr", "max_iter": max_iter, "check_limits": check_limits},
            "status": step2.status.value,
            "result": step2.data if step2.data else {"error": step2.error},
        },
    ]
    task_inputs = {
        "case": case,
        "max_iter": max_iter,
        "check_limits": check_limits,
    }
    prompt = (
        f"Using the PowerMCP tools, load case '{case}' and run an AC power flow "
        f"(method=nr, max_iter={max_iter}, check_limits={check_limits}). Show the "
        f"tool calls and their results."
    )
    lines = []
    for k, s in enumerate(trajectory):
        lines.append(f"Step {k+1}: {s['tool']}({s['args']}) -> status={s['status']}")
        res = s["result"]
        if "error" in res:
            lines.append(f"  result: error: {res['error']}")
        else:
            brief = {kk: res.get(kk) for kk in ("buses", "iterations", "status", "min_bus_voltage_pu", "max_bus_voltage_pu", "max_line_loading_percent", "voltage_violations") if res.get(kk) is not None}
            lines.append(f"  result: {brief}")
    answer = "\n".join(lines)

    # Evidence from the run_power_flow step (the solver-bearing call).
    if step2.evidence is not None:
        evidence = step2.evidence
    else:
        evidence = pm.PowerMCP._canonical_evidence(
            case_id=case, tool_name="run_power_flow",
            input_hash=input_hash if isinstance(input_hash, str) else "sha256:unknown",
            status=step2.status, result_payload={"error": step2.error},
            diagnostics=[step2.error or ""], physical_valid=False,
        )
    validity = {
        pm.ExecutionStatus.SUCCESS: "valid",
        pm.ExecutionStatus.CONSTRAINT_VIOLATION: "constraint_violation",
        pm.ExecutionStatus.NON_CONVERGENCE: "non_convergence",
        pm.ExecutionStatus.EXECUTION_FAILURE: "execution_failure",
    }[step2.status]
    structured = {"trajectory": trajectory}
    example_id = common.compute_example_id(family, subfamily, case, seed, task_inputs)
    return {
        "example_id": example_id,
        "family": family,
        "subfamily": subfamily,
        "topology": case,
        "seed": seed,
        "task": {"prompt": prompt, "inputs": task_inputs},
        "expected": {"answer": answer, "structured": structured, "validity": validity},
        "execution": {
            "case_id": evidence["case_id"],
            "solver": evidence["solver"],
            "solver_version": evidence["solver_version"],
            "input_hash": evidence["input_hash"],
            "result_hash": evidence["result_hash"],
            "status": evidence["status"],
            "iterations": (step2.data or {}).get("iterations"),
            "execution_time_s": step2.execution_time_s,
        },
        "provenance": common.build_provenance(
            base_seed,
            source_refs=[f"case:{case}", "wattson/inference/powermcp.py", "MISSION.md#M04"],
        ),
        "lifecycle": {"status": "verified" if step2.status in (pm.ExecutionStatus.SUCCESS, pm.ExecutionStatus.CONSTRAINT_VIOLATION) else "quarantined",
                      "split": None,
                      "rejection_reason": None if step2.status in (pm.ExecutionStatus.SUCCESS, pm.ExecutionStatus.CONSTRAINT_VIOLATION) else "trajectory ended non-converged / failed"},
    }


