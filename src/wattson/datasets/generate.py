#!/usr/bin/env python3
"""NEM PowerCoder M04 dataset factory -- the GENERATE stage.

Builds a solver-verified, provenance-complete training dataset by generating
parameterised tasks from a deterministic seed, executing each against REAL
pandapower Newton-Raphson power flow (reusing the M02 canonical execution
layer, wattson.inference.powermcp), and recording the solver's own output
as the expected result. No expected value is hand-written or fabricated.

Subfamilies (task templates) generated by this smoke run:

- power-flow-contingency / pf-report          -- run power flow (base or N-1
  line contingency) and report the solver's measurements.
- power-flow-contingency / pf-load-scale-fit  -- fit the global load scale
  factor so a named bus's voltage hits a target (real bisection over real
  pp.runpp calls).
- power-flow-contingency / pf-line-rating-fit -- fit a line's rating scale so
  its loading hits a target.
- power-flow-contingency / pf-gen-dispatch-fit-- fit a generator's dispatch
  scale so a named transformer's loading hits a target.
- powermcp-trajectories / mcp-trajectory      -- a short PowerMCP tool-call
  trajectory (load_network -> run_power_flow) with real tool results.

Determinism (MISSION.md M04 acceptance: "repeated generation with identical
inputs produces the same task definitions and expected solver results"):
  - Per-example seed = sha256(base_seed | family | subfamily | topology |
    index) -> 64-bit int (common.derive_example_seed). Same base seed + counts
    -> same seeds -> same element picks, targets, and (on the same pinned
    pandapower/numba stack) same solver outputs.
  - example_id = 'ex_' + 16 hex of sha256 over the canonical task definition,
    so identical inputs always produce the same ID.

Named stand-ins (per AGENTS.md): the fit families' "propose the next trial"
step is gridfit.bisection_fit (a deterministic closed-form search), not an LLM
-- the live-LLM path is M03's concern (labs/03 .../llm_provider.py). The
fixture-2bus-ok network is the deterministic SUCCESS-branch stand-in from M02.
The snem-1803 case is deliberately excluded here (it is an EXECUTION_FAILURE in
pandapower 3.5.4) and is reserved for the code-repair family.

Usage:
    uv run python wattson/datasets/generate.py \
        --base-seed 42 --out-dir wattson/datasets/smoke
"""

