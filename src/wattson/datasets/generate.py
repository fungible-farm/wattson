def generate_dataset(
    base_seed: int,
    counts: dict[str, int],
    element_lists: dict[str, Any],
) -> list[dict[str, Any]]:
    """Generate the full dataset (all subfamilies) and return the example list.

    Element lists are keyed by subfamily; the discovery script wrote
    'load_scale_buses', 'line_rating_lines', 'gen_dispatch' for snem-sa-2000.
    """
    cache = EndpointCache()
    elements_by_subfamily: dict[str, list[Any]] = {
        "pf-load-scale-fit": element_lists["load_scale_buses"],
        "pf-line-rating-fit": element_lists["line_rating_lines"],
        "pf-gen-dispatch-fit": element_lists["gen_dispatch_pairs"],
    }
    examples: list[dict[str, Any]] = []
    for subfamily, count in counts.items():
        cases = SUBFAMILY_CASES[subfamily]
        for i in range(count):
            case = cases[i % len(cases)]
            if subfamily == "pf-report":
                ex = _gen_pf_report_example(case, i, base_seed)
            elif subfamily == "mcp-trajectory":
                ex = _gen_mcp_trajectory_example(case, i, base_seed)
            else:
                ex = _gen_fit_example(subfamily, case, elements_by_subfamily[subfamily], i, base_seed, cache)
            examples.append(ex)
    return examples


def build_manifest(
    examples: list[dict[str, Any]],
    base_seed: int,
    counts: dict[str, int],
) -> dict[str, Any]:
    """Build the dataset manifest (MISSION.md M04: hashes + licence)."""
    by_subfamily: dict[str, int] = {}
    by_family: dict[str, int] = {}
    by_status: dict[str, int] = {}
    for ex in examples:
        by_subfamily[ex["subfamily"]] = by_subfamily.get(ex["subfamily"], 0) + 1
        by_family[ex["family"]] = by_family.get(ex["family"], 0) + 1
        by_status[ex["lifecycle"]["status"]] = by_status.get(ex["lifecycle"]["status"], 0) + 1
    # A manifest-level content hash over the sorted example IDs (a stable
    # fingerprint of the whole dataset for this seed/counts).
    id_hash = common.sha256_prefixed(
        common.canonical_json(sorted(ex["example_id"] for ex in examples)).encode("utf-8")
    )
    return {
        "dataset": "nem-wattson-smoke",
        "version": common.GENERATOR_VERSION,
        "generator": common.GENERATOR_NAME,
        "base_seed": base_seed,
        "total_examples": len(examples),
        "counts_by_subfamily": by_subfamily,
        "counts_by_family": by_family,
        "counts_by_lifecycle_status": by_status,
        "requested_counts": counts,
        "content_hash": id_hash,
        "licence": common.DATA_LICENCE,
        "git_commit": common.git_commit(),
        "created_utc": common.utc_now_iso(),
        "solver": "pandapower",
        "solver_version": pp.__version__,
        "notes": (
            "500-example smoke dataset (MISSION.md M04). All expected values are "
            "real pandapower solver output. snem-1803 excluded (EXECUTION_FAILURE; "
            "reserved for code-repair family). See schemas/training-example.schema.json."
        ),
    }


def main(argv: Optional[list[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the NEM PowerCoder M04 smoke dataset.")
    ap.add_argument("--base-seed", type=int, default=42, help="Deterministic base seed (default 42).")
    ap.add_argument("--count-per-subfamily", type=int, default=None,
                    help="Override: use this count for EVERY subfamily (quick smoke). Default: DEFAULT_COUNTS (sums to 500).")
    ap.add_argument("--out-dir", type=Path, default=REPO_ROOT / "wattson" / "datasets" / "smoke",
                    help="Output directory (examples.jsonl + manifest.json).")
    ap.add_argument("--element-lists", type=Path,
                    default=REPO_ROOT / "wattson" / "datasets" / "element_lists.json",
                    help="Path to the curated element lists JSON.")
    args = ap.parse_args(argv)

    if args.count_per_subfamily is not None:
        counts = {sf: args.count_per_subfamily for sf in DEFAULT_COUNTS}
    else:
        counts = dict(DEFAULT_COUNTS)

    print(f"[generate] base_seed={args.base_seed} counts={counts} total={sum(counts.values())}")
    element_lists = _load_element_lists(args.element_lists)
    t0 = time.monotonic()
    examples = generate_dataset(args.base_seed, counts, element_lists)
    elapsed = time.monotonic() - t0

    common.write_jsonl(args.out_dir / "examples.jsonl", examples)
    manifest = build_manifest(examples, args.base_seed, counts)
    common.write_json(args.out_dir / "manifest.json", manifest)

    print(f"[generate] wrote {len(examples)} examples in {elapsed:.1f}s")
    print(f"[generate]   -> {args.out_dir / 'examples.jsonl'}")
    print(f"[generate]   -> {args.out_dir / 'manifest.json'}")
    print(f"[generate] lifecycle: {manifest['counts_by_lifecycle_status']}")
    print(f"[generate] subfamilies: {manifest['counts_by_subfamily']}")
    return 0


